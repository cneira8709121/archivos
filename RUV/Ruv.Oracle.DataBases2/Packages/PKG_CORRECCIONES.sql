  BEGIN

    UPDATE TBCORRECCION SET ID_USUARIO    = PI_IDCORRECCION,
                            OBSERVACIONES = PI_OBSERVACION,
                            ESTADO        = RECHAZADO
                        WHERE ID = PI_IDCORRECCION;

  END;

  PROCEDURE SP_CONSULTARCAMPOSCORRECCION(PI_IDCORRECCION IN NUMBER,
                                         PO_CURSOR OUT CURSOR_TYPE
                                        ) IS

  BEGIN

    OPEN PO_CURSOR FOR
      SELECT CC.CAMPO, CC.VALORNUEVO VALOR
        FROM TBCORRECCIONCAMPOS CC
        WHERE ID_CORRECCION = PI_IDCORRECCION;

  END;

  FUNCTION OBTENERVALORANTERIOR(PI_ID_REGPERSONA IN NUMBER,
                                PI_CAMPO IN NUMBER
                               ) RETURN VARCHAR2
                                IS
  RETURN_VALUE VARCHAR2(500);
  V_IDPERSONA NUMBER;
  V_DISCAPACIDAD VARCHAR2(300);
  VLIST PKG_SERIALIZATION.NUMBERVARRAY;

  BEGIN

    SELECT ID_PERSONA INTO V_IDPERSONA FROM TBREGISTROS_PERSONAS WHERE ID = PI_ID_REGPERSONA;

    CASE
      WHEN PI_CAMPO = PRIMERNOMBRE THEN
        SELECT PRIMERNOMBRE INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = SEGUNDONOMBRE THEN
        SELECT SEGUNDONOMBRE INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = PRIMERAPELLIDO THEN
        SELECT PRIMERAPELLIDO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = SEGUNDOAPELLIDO THEN
        SELECT SEGUNDOAPELLIDO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = TIPODOCUMENTO THEN
        SELECT PARAM_TIPODOCUMENTO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = DOCUMENTO THEN
        SELECT NUMERODOCUMENTO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = FECHANACIMIENTO THEN
        SELECT FECHANACIMIENTO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = GENERO THEN
        SELECT PARAM_GENERO INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = ETNIA THEN
        SELECT PARAM_ETNIAPERTENECE INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;
      WHEN PI_CAMPO = DISCAPACIDADES THEN
        SELECT PARAM_DISCAPACIDAD BULK COLLECT INTO VLIST
          FROM TBDISCAPACIDAD_PERSONA WHERE ID_REGPERSONA = PI_ID_REGPERSONA;
        RETURN_VALUE := PKG_SERIALIZATION.Serialize(VLIST);
      WHEN PI_CAMPO = DIRECCION THEN
        SELECT DIRECCION INTO RETURN_VALUE FROM TBREGISTROS_PERSONAS WHERE ID = PI_ID_REGPERSONA;
      WHEN PI_CAMPO = TELEFONO THEN
        SELECT TELEFONO INTO RETURN_VALUE FROM TBREGISTROS_PERSONAS WHERE ID = PI_ID_REGPERSONA;
      WHEN PI_CAMPO = CORREOELECTRONICO THEN
        SELECT EMAIL INTO RETURN_VALUE FROM TBREGISTROS_PERSONAS WHERE ID = PI_ID_REGPERSONA;
     WHEN PI_CAMPO = SUBETNIA THEN
        SELECT PARAM_MINORIAETNICA INTO RETURN_VALUE FROM TBPERSONAS WHERE ID = V_IDPERSONA;

    END CASE;

    RETURN RETURN_VALUE;

  END OBTENERVALORANTERIOR;

  FUNCTION OBTENERVALORCORRECCION(PI_IDCORRECCION IN NUMBER,
                                  PI_CAMPO IN NUMBER
                                 ) RETURN VARCHAR2
                                  IS
  RETURN_VALUE VARCHAR2(500);

  BEGIN

    SELECT VALORNUEVO INTO RETURN_VALUE
      FROM TBCORRECCIONCAMPOS
      WHERE ID_CORRECCION = PI_IDCORRECCION AND
            CAMPO         = PI_CAMPO;

    RETURN RETURN_VALUE;

  END OBTENERVALORCORRECCION;

  PROCEDURE SP_APROBARSOLICITUD(PI_IDCORRECCION IN NUMBER) IS
      V_IDREGPERSONA NUMBER;
      V_IDPERSONA    NUMBER;
    BEGIN
      SELECT ID_REGPERSONA INTO V_IDREGPERSONA FROM TBCORRECCION WHERE ID = PI_IDCORRECCION;
      SELECT ID_PERSONA    INTO V_IDPERSONA FROM TBREGISTROS_PERSONAS WHERE ID = V_IDREGPERSONA;
      -- CAMBIAR ESTADO DE LA CORRECION
      UPDATE TBCORRECCION SET ESTADO = APROBADO WHERE ID = PI_IDCORRECCION;


      -- BUSCAR LOS CAMPOS
      FOR X IN (SELECT CC.CAMPO, CC.VALORNUEVO FROM TBCORRECCIONCAMPOS CC
                WHERE CC.ID_CORRECCION = PI_IDCORRECCION) LOOP
        IF X.CAMPO = PRIMERNOMBRE THEN
          UPDATE TBPERSONAS SET PRIMERNOMBRE = X.VALORNUEVO WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = SEGUNDONOMBRE THEN
          UPDATE TBPERSONAS  SET SEGUNDONOMBRE = X.VALORNUEVO WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = PRIMERAPELLIDO THEN
          UPDATE TBPERSONAS SET PRIMERAPELLIDO = X.VALORNUEVO WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = SEGUNDOAPELLIDO THEN
          UPDATE TBPERSONAS SET SEGUNDOAPELLIDO = X.VALORNUEVO WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = TIPODOCUMENTO THEN
          UPDATE TBPERSONAS SET PARAM_TIPODOCUMENTO = CAST(X.VALORNUEVO AS NUMBER) WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = DOCUMENTO THEN
          UPDATE TBPERSONAS SET NUMERODOCUMENTO = X.VALORNUEVO WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = FECHANACIMIENTO THEN
          UPDATE TBPERSONAS SET FECHANACIMIENTO = CAST(X.VALORNUEVO AS DATE) WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = GENERO THEN
          UPDATE TBPERSONAS SET PARAM_GENERO = CAST(X.VALORNUEVO AS NUMBER) WHERE ID = V_IDPERSONA;


        ELSIF X.CAMPO = ETNIA THEN
          UPDATE TBPERSONAS SET PARAM_ETNIAPERTENECE = CAST(X.VALORNUEVO AS NUMBER) WHERE ID = V_IDPERSONA;

        ELSIF X.CAMPO = SUBETNIA THEN
          UPDATE TBPERSONAS SET PARAM_MINORIAETNICA = CAST(X.VALORNUEVO AS NUMBER) WHERE ID = V_IDPERSONA;

        ELSIF X.CAMPO = DIRECCION THEN
          UPDATE TBREGISTROS_PERSONAS SET DIRECCION = X.VALORNUEVO WHERE ID = V_IDREGPERSONA;


        ELSIF X.CAMPO = CORREOELECTRONICO  THEN
          UPDATE TBREGISTROS_PERSONAS SET EMAIL = X.VALORNUEVO WHERE ID = V_IDREGPERSONA;


        ELSIF X.CAMPO = TELEFONO THEN
          UPDATE TBREGISTROS_PERSONAS SET TELEFONO = X.VALORNUEVO WHERE ID = V_IDREGPERSONA;


        ELSIF X.CAMPO = DISCAPACIDADES THEN
          DELETE FROM TBDISCAPACIDAD_PERSONA WHERE ID_REGPERSONA = V_IDREGPERSONA;

          DECLARE
            V_DISCAPACIDAD PKG_SERIALIZATION.NUMBERVARRAY;
          BEGIN
            V_DISCAPACIDAD := PKG_SERIALIZATION.DESERIALIZE(X.VALORNUEVO);
            IF V_DISCAPACIDAD.COUNT > 0 THEN
              FOR Z IN V_DISCAPACIDAD.FIRST..V_DISCAPACIDAD.LAST LOOP
                INSERT INTO TBDISCAPACIDAD_PERSONA (ID_REGPERSONA, PARAM_DISCAPACIDAD, ACTIVO)
                VALUES (V_IDREGPERSONA, V_DISCAPACIDAD(Z), 1);
              END LOOP;
            END IF;
          END;
        END IF;
      END LOOP;
    END;

 FUNCTION F_USUARIOMENOSCARGACORRECCION( P_Rol NUMBER )
  RETURN NUMBER IS Result NUMBER;
  BEGIN

    SELECT ID
    INTO   Result
    FROM   (SELECT ID
            FROM   ( SELECT RU.id_usuario AS Id, COUNT(NVL(CC.ID_USUARIO, 0)) AS CONTADOR
                     FROM   tbroles_usuario RU
                     INNER JOIN TBUSUARIOS   UU ON (UU.ID = RU.ID_USUARIO AND UU.ACTIVO = 1)
                     LEFT  JOIN TBCORRECCION CC ON (RU.ID_USUARIO = CC.ID_USUARIO)
                     WHERE  RU.id_rol = P_Rol
                     GROUP BY RU.id_usuario
                     ORDER BY CONTADOR ASC)
             WHERE ROWNUM = 1);
    RETURN (RESULT);
  END;

