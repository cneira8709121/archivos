           , OBTENERVALORCORRECCION(PI_IDCORRECCION, PRIMERAPELLIDO) PRIMERAPELLIDO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, SEGUNDOAPELLIDO) SEGUNDOAPELLIDO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, TIPODOCUMENTO) PARAM_TIPODOCUMENTO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, DOCUMENTO) NUMERODOCUMENTO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, FECHANACIMIENTO) FECHANACIMIENTO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, GENERO) PARAM_GENERO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, ETNIA) PARAM_ETNIAPERTENECE
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, SUBETNIA) PARAM_MINORIAETNICA
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, DISCAPACIDADES) DISCAPACIDAD
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, DIRECCION) DIRECCION
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, TELEFONO) TELEFONO
           , OBTENERVALORCORRECCION(PI_IDCORRECCION, CORREOELECTRONICO) CORREOELECTRONICO
      FROM DUAL;

  END;

  PROCEDURE SP_RECHAZARCORRECCION(PI_IDCORRECCION IN NUMBER,
                                   PI_IDUSUARIORECHAZA IN NUMBER,
                                   PI_OBSERVACION in VARCHAR
