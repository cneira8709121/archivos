create or replace PACKAGE BODY PKG_CORRECCIONES AS

  PROCEDURE SP_OBTENERINFOCORRECCION (PI_IDCORRECCION IN NUMBER,
                                      PO_CURSOR OUT CURSOR_TYPE)AS

  BEGIN
   OPEN PO_CURSOR FOR
   SELECT CR.ID,
          CR.ID_REGPERSONA,
          CR.ID_USUARIOSOLICITUD,
          CR.ID_USUARIO,
          CR.FECHASOLICITUD,
          CR.OBSERVACIONES,
          CR.ESTADO
   FROM TBCORRECCION CR
   WHERE CR.ID = PI_IDCORRECCION;
  END;

  PROCEDURE SP_CARGADATOSCORREGIR(PI_IDREGPERSONA IN NUMBER,
                                  PO_CURSOR OUT CURSOR_TYPE
                                 ) IS

    V_DISCAPACIDAD VARCHAR2(300);
    VLIST PKG_SERIALIZATION.NUMBERVARRAY;
  BEGIN
    SELECT PARAM_DISCAPACIDAD BULK COLLECT INTO VLIST
    FROM TBDISCAPACIDAD_PERSONA WHERE ID_REGPERSONA = PI_IDREGPERSONA;
    V_DISCAPACIDAD := PKG_SERIALIZATION.Serialize(VLIST);

    OPEN PO_CURSOR FOR
      SELECT P.PRIMERNOMBRE
           , P.SEGUNDONOMBRE
           , P.PRIMERAPELLIDO
           , P.SEGUNDOAPELLIDO
           , P.PARAM_TIPODOCUMENTO
           , P.NUMERODOCUMENTO
           , P.FECHANACIMIENTO
           , P.PARAM_GENERO
           , P.PARAM_ETNIAPERTENECE
           , V_DISCAPACIDAD AS DISCAPACIDAD
           , RP.DIRECCION
           , RP.EMAIL
           , RP.TELEFONO
      FROM TBREGISTROS_PERSONAS RP
      INNER JOIN TBPERSONAS P ON P.ID = RP.ID_PERSONA
      WHERE RP.ID = PI_IDREGPERSONA;
    END;

  PROCEDURE SP_SOLICITARCORRECCION(PI_IDREGPERSONA IN NUMBER,
                                   PI_IDUSUARIOSOLICITUD IN NUMBER,
                                   PI_CAMPOSCORRECCIONES IN VARCHAR,
                                   PI_VALORESCORRECCIONES IN VARCHAR,
                                   PO_IDCORRECCION OUT NUMBER
                                  ) IS

    V_IDCAMPOS       PKG_COMMON.STRING_ARRAY;
    V_IDVALORES      PKG_COMMON.STRING_ARRAY;
    V_IDCORRECCION   NUMBER;
    V_VALORANTERIOR  VARCHAR(500);
    V_USUARIOMENENOSCARGA NUMBER;

  BEGIN

    V_USUARIOMENENOSCARGA:=PKG_CORRECCIONES.F_USUARIOMENOSCARGACORRECCION(ROL);

    SELECT SEQ_TBCORRECCION.NEXTVAL INTO V_IDCORRECCION FROM DUAL;
    PO_IDCORRECCION := V_IDCORRECCION;

    --_______________Cabecera_________________
    INSERT
    INTO TBCORRECCION
      (
        ID,
        ID_REGPERSONA,
        ID_USUARIOSOLICITUD,
        ID_USUARIO,
        FECHASOLICITUD,
        ESTADO
      )
      VALUES
      (
        V_IDCORRECCION,
        PI_IDREGPERSONA,
        PI_IDUSUARIOSOLICITUD,
        V_USUARIOMENENOSCARGA,
        SYSDATE,
        PENDIENTE
      );
    --_______________________________________

    --_______________Detalle_________________

      V_IDCAMPOS := PKG_COMMON.SPLIT_STRING(PI_CAMPOSCORRECCIONES);
      V_IDVALORES := PKG_COMMON.SPLIT_STRING(PI_VALORESCORRECCIONES);

      IF V_IDCAMPOS.count > 0 THEN
        FOR I IN 1..V_IDCAMPOS.COUNT LOOP

          V_VALORANTERIOR := OBTENERVALORANTERIOR(PI_IDREGPERSONA, V_IDCAMPOS(I));

          INSERT
          INTO TBCORRECCIONCAMPOS
            (
              ID,
              ID_CORRECCION,
              CAMPO,
              VALORANTERIOR,
              VALORNUEVO
            )
            VALUES
            (
              SEQ_TBCORRECCIONCAMPOS.NEXTVAL,
              V_IDCORRECCION,
              V_IDCAMPOS(I),
              V_VALORANTERIOR,
              V_IDVALORES(I)
            );

        END LOOP;
      END IF;

    --_______________________________________

  END;

  PROCEDURE SP_BUSCAPERSONASCOUNT(PI_NUMEROFORMULARIO IN VARCHAR2,
                                  PI_PRIMERNOMBRE     IN VARCHAR2,
                                  PI_PRIMERAPELLIDO   IN VARCHAR2,
                                  PI_NUMERODOCUMENTO  IN VARCHAR2,
                                  PO_RECORDCOUNT      OUT NUMBER) IS
  BEGIN
    SELECT COUNT(1) INTO PO_RECORDCOUNT
    FROM TBREGISTROS_PERSONAS RP
    INNER JOIN TBPERSONAS      PP ON (PP.ID = RP.ID_PERSONA)
    INNER JOIN TBDECLARACIONES DD ON (DD.ID = RP.ID_DECLARACION)
    WHERE DD.NUMEROFORMULARIO = NVL(pi_NumeroFormulario, DD.NUMEROFORMULARIO)
      AND PP.NUMERODOCUMENTO  = NVL(pi_NumeroDocumento , PP.NUMERODOCUMENTO)
      AND UPPER(PP.PRIMERNOMBRE)   LIKE '%' || UPPER(NVL(pi_PrimerNombre  , PP.PRIMERNOMBRE)) || '%'
      AND UPPER(PP.PRIMERAPELLIDO) LIKE '%' || UPPER(NVL(pi_PrimerApellido, PP.PRIMERAPELLIDO)) || '%';
  END;

  PROCEDURE SP_BUSCAPERSONAS(PI_NUMEROFORMULARIO IN VARCHAR2,
                             PI_PRIMERNOMBRE     IN VARCHAR2,
                             PI_PRIMERAPELLIDO   IN VARCHAR2,
                             PI_NUMERODOCUMENTO  IN VARCHAR2,
                             PI_PAGENUMBER       IN NUMBER,
                             PI_PAGESIZE         IN NUMBER,
                             PO_CURSOR           OUT CURSOR_TYPE) IS
    LOWERBOUND NUMBER;
    UPPERBOUND NUMBER;
  BEGIN
     LOWERBOUND := (PI_PAGENUMBER * PI_PAGESIZE) + 1;
    UPPERBOUND := ((PI_PAGENUMBER - 1) * PI_PAGESIZE) + 1;
 
    OPEN PO_CURSOR FOR
      SELECT *
      FROM(
            SELECT INFO.*, ROWNUM AS R
            FROM(
                  SELECT RP.ID               AS NIDREGISTROPRESONA
                       , DD.NUMEROFORMULARIO AS NUMEROFORMULARIO
                       , P2.NOMBRE           AS ESTADOPROCESO
                       , DD.FECHADECLARACION AS FECHADECLARACION
                       , M.NOMBRE            AS MUNICIPIO
                       , D.NOMBRE            AS DEPARTAMENTO
                       , P.NOMBRE            AS PAIS
                       , PP.PRIMERNOMBRE     AS PRIMERNOMBRE
                       , PP.SEGUNDONOMBRE    AS SEGUNDONOMBRE
                       , PP.PRIMERAPELLIDO   AS PRIMERAPELLIDO
                       , PP.SEGUNDOAPELLIDO  AS SEGUNDOAPELLIDO
                       , P1.NOMBRE           AS TIPODOCUMENTO
                       , PP.NUMERODOCUMENTO  AS NUMERODOCUMENTO
                       , DD.ID               AS ID
                  FROM TBREGISTROS_PERSONAS     RP
                  INNER JOIN TBPERSONAS         PP ON (PP.ID = RP.ID_PERSONA)
                  INNER JOIN TBDECLARACIONES    DD ON (DD.ID = RP.ID_DECLARACION)
                  INNER JOIN TBPARAMETROS       P1 ON (P1.ID = PP.PARAM_TIPODOCUMENTO)
                  INNER JOIN TBPARAMETROS       P2 ON (P2.ID = DD.PARAM_ESTADO)
                  LEFT  JOIN TBENTIDADMUNICIPIO EM ON (EM.ID = DD.ID_ENTIDADMUNICIPIODECLARACION)
                  LEFT  JOIN TBGEOGRAFIA        M ON M.ID = EM.ID_MUNICIPIO
                  LEFT  JOIN TBGEOGRAFIA        D ON D.ID = M.PADREID
                  LEFT  JOIN TBGEOGRAFIA        P ON P.ID = D.PADREID
                  WHERE DD.NUMEROFORMULARIO = NVL(pi_NumeroFormulario, DD.NUMEROFORMULARIO)
                    AND NVL(PP.NUMERODOCUMENTO,-1)  = NVL(pi_NumeroDocumento , -1)
                    AND UPPER(PP.PRIMERNOMBRE)   LIKE '%' || UPPER(NVL(pi_PrimerNombre  , PP.PRIMERNOMBRE)) || '%'
                    AND UPPER(PP.PRIMERAPELLIDO) LIKE '%' || UPPER(NVL(pi_PrimerApellido, PP.PRIMERAPELLIDO)) || '%'
                ) INFO
            WHERE ROWNUM < LOWERBOUND)
      WHERE R >= UPPERBOUND;        
  END;

  PROCEDURE SP_CONSULTARCORRECCION(PI_IDCORRECCION IN NUMBER,
                                   PO_CURSOR OUT CURSOR_TYPE
                                  ) IS

    V_DISCAPACIDAD VARCHAR2(300);
    VLIST PKG_SERIALIZATION.NUMBERVARRAY;
    V_ID_REGPERSONA NUMBER;
