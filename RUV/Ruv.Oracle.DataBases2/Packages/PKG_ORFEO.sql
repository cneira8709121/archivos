TYPE CURSOR_TYPE IS REF CURSOR;

PROCEDURE SP_GETORFEOPORIDVALORACION(PI_IDVALORACION IN NUMBER,
                                     PO_CURSOR OUT CURSOR_TYPE);
/*	DESCRIPCION: INSERTA UN NUEVO CODIGO ORFEO GENERADO POR EL SERVICIO Y LO RELACIONA
