  /* Guarda el estado del proceso? PENDIENTE QUITAR SI NO SE USA */
  PROCEDURE SP_GUARDAR_ESTADO_PROCESO
  (
    P_ID_ESTADO_PROCESO     IN NUMBER
   ,P_ID_USUARIO            IN NUMBER
   ,P_PARAM_PROCESO         IN NUMBER
   ,P_ID_PROCESO            IN NUMBER
   ,P_ESTADO_FIN            OUT NUMBER
   ,P_ID_DETALLE_RADICACION OUT NUMBER
  ) AS
    V_ID              NUMBER;
    V_ID_UTERRITORIAL NUMBER := 0;
    V_ESTADO_INI      NUMBER;
  BEGIN
    P_ID_DETALLE_RADICACION := NULL;

    V_ESTADO_INI := -1;

    IF (P_ID_ESTADO_PROCESO IS NOT NULL) THEN
      SELECT PARAM_ESTADO
        INTO V_ESTADO_INI
        FROM TBESTADOPROCESOS
       WHERE ID = P_ID_ESTADO_PROCESO;
    END IF;

    SELECT ID_UTRERRITORIAL
      INTO V_ID_UTERRITORIAL
      FROM TBUSUARIOS
     WHERE ID = P_ID_USUARIO;

    -- No existe ningun registro en la base de datos

    IF (V_ESTADO_INI = -1) THEN
      SELECT SEQ_ESTADO_PROCESO.NEXTVAL INTO V_ID FROM DUAL;

      INSERT INTO TBESTADOPROCESOS
        (ID,
         ID_USUARIO,
         PARAM_ESTADO,
         FECHAPROCESO,
         PARAM_PROCESO,
         ID_UTERRITORIAL,
         ID_PROCESO)
      VALUES
        (V_ID,
         P_ID_USUARIO,
         INICIO_CAPTURA_SINRADICAR,
         SYSDATE,
         P_PARAM_PROCESO,
         V_ID_UTERRITORIAL,
         P_ID_PROCESO);

      P_ESTADO_FIN := INICIO_CAPTURA_SINRADICAR;
    END IF;

    IF (V_ESTADO_INI = INICIO_CAPTURA_SINRADICAR OR
       V_ESTADO_INI = INICIA_MOD_NORADICA) THEN
      P_ESTADO_FIN := FINALIZA_CAPTURA_SINRADICAR;
      
    ELSIF (V_ESTADO_INI = INICIA_MOD_NOPEND_VALORAR) THEN
      P_ESTADO_FIN := VALORACION_FINALIZADA;

      -- 17-Jan-2011 NAFR: Nuevo estado.
    ELSIF (V_ESTADO_INI = RESTAURACION_FRAUDE_TIPO_1) THEN
      P_ESTADO_FIN := VALORACION_PEND_PORASIGNAR;

    ELSIF (V_ESTADO_INI = RADICADO_PENDIENTE_CAPTURA) THEN
      SELECT ID_DETALLE_RADICACION
        INTO P_ID_DETALLE_RADICACION
        FROM TBESTADOPROCESOS
       WHERE ID = P_ID_ESTADO_PROCESO;

      P_ESTADO_FIN := RADICADO_INICIA_CAPTURA;

      UPDATE TBESTADOPROCESOS
         SET ID_PROCESO = P_ID_PROCESO
       WHERE ID = P_ID_ESTADO_PROCESO;

    ELSIF (V_ESTADO_INI = PENDIENTE_POR_VALORAR) THEN
      P_ESTADO_FIN := INICIA_VALORACION;

    ELSIF (V_ESTADO_INI = INICIA_VALORACION) THEN
      P_ESTADO_FIN := VALORACION_FINALIZADA;

    ELSIF (V_ESTADO_INI = VALORACION_FINALIZADA) THEN
      P_ESTADO_FIN := INICIA_VALORACION;

    ELSIF (V_ESTADO_INI = RADICADO_INICIA_CAPTURA OR
          V_ESTADO_INI = INICIA_MOD_FIN OR
          V_ESTADO_INI = INICIA_MOD_PEND_VALORAR) THEN
      P_ESTADO_FIN := PROCESO_FINALIZADO;

      IF (PROCESO_DECLARACION = P_PARAM_PROCESO) THEN
        P_ESTADO_FIN := VALORACION_PEND_PORASIGNAR;
      END IF;

    ELSIF (V_ESTADO_INI = VALORACION_PEND_PORASIGNAR) THEN
      P_ESTADO_FIN := INICIA_MOD_PEND_VALORAR;

    ELSIF (V_ESTADO_INI = FINALIZA_CAPTURA_SINRADICAR) THEN
      P_ESTADO_FIN := INICIA_MOD_NORADICA;

    ELSIF (V_ESTADO_INI = PROCESO_FINALIZADO) THEN
      P_ESTADO_FIN := INICIA_MOD_FIN;

    END IF;

    IF (V_ESTADO_INI != -1) THEN
      UPDATE TBESTADOPROCESOS
         SET ID_USUARIO      = P_ID_USUARIO,
             ID_UTERRITORIAL = V_ID_UTERRITORIAL,
             PARAM_ESTADO    = P_ESTADO_FIN,
             FECHAPROCESO    = SYSDATE
       WHERE ID = P_ID_ESTADO_PROCESO;
    END IF;

  END;

