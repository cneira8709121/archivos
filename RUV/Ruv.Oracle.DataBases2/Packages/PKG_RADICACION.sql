  PROCEDURE SP_UPDRADICACION
   (
    P_ID                            IN OUT NUMBER,
    P_ID_MUNICIPIO                  NUMBER DEFAULT NULL,
    P_PARAM_TIPOENTIDAD             NUMBER DEFAULT NULL,
    P_NRO_FORMULARIO                VARCHAR2,
    P_NRO_ID_TIPO_RADICACION        NUMBER,
    P_OBSERVACIONES                 VARCHAR2 DEFAULT NULL,
    P_RUTAIMAGEN                    VARCHAR2,
    P_ID_ENTIDADMUNICIPIO           NUMBER DEFAULT NULL,
    P_PARAM_RESULTADO_VALIDACION    NUMBER DEFAULT NULL
   )
   AS

  V_RADICA NUMBER;
  V_ID_DECLARACION NUMBER;
  ID_USUARIOASIGNADO NUMBER;
  CFORMULARIO VARCHAR2(20);
  V_PAISDECLARACION NUMBER;
  V_DPTODECLARACION NUMBER;

   BEGIN
     SELECT D.PADREID INTO V_DPTODECLARACION FROM TBGEOGRAFIA D WHERE D.ID =  P_ID_MUNICIPIO;
      SELECT P.PADREID INTO V_PAISDECLARACION FROM TBGEOGRAFIA P WHERE P.ID =  V_DPTODECLARACION;
      INSERT INTO TBRADICACION_HISTORICO SELECT SEQ_TBRADICAHISTORICO.NEXTVAL,R.ID, R.NRO_FORMULARIO,
      R.ID_ENTIDADMUNICIPIO,R.OBSERVACIONES,SYSDATE,R.ID_USUARIO_RADICA  FROM TBRADICACION R
      WHERE R.ID = P_ID ;

      -- Si el número de formulario cambió, éste debe ser actualizado en la tabla de declaraciones
      SELECT      D.ID, D.NUMEROFORMULARIO INTO V_ID_DECLARACION, CFORMULARIO
      FROM        TBRADICACION R
      INNER JOIN  TBDECLARACIONES D ON D.ID = R.ID_DECLARACION
      WHERE       R.ID = P_ID;

      --En caso de que el numero de formulario sea nulo
      --IF CFORMULARIO IS NULL THEN
      --  CFORMULARIO := '';
      --END IF;

      IF CFORMULARIO <> P_NRO_FORMULARIO OR CFORMULARIO IS NULL THEN
          UPDATE  TBDECLARACIONES
          SET     NUMEROFORMULARIO = P_NRO_FORMULARIO
          WHERE   ID_DETALLERADICACION = P_ID;
      END IF;

      -- SI EL RESULTADO DE LA VALIDACIï¿½N DEL FORMULARIO NO ES NULO, SE EVALï¿½A SU ESTADO Y SE ACTUALIZAN
      -- LAS TABLAS DE RADICACIï¿½N, DECLARACIï¿½N E IDENTIFICADOR FORMULARIO
      IF P_PARAM_RESULTADO_VALIDACION IS NOT NULL THEN
        IF P_PARAM_RESULTADO_VALIDACION = VALIDACION_CORRECTA THEN
          ID_USUARIOASIGNADO := pkg_common.F_USUARIOMENOSCARGA(ROL_CRITICA_5);
          PKG_COMMON.SP_UPDESTADO_DECLARACION(V_ID_DECLARACION, ID_USUARIOASIGNADO, RAD_PENDIENTE_POR_CRITICA_5);

          UPDATE TBIDENTIFICADORFORMULARIO
          SET    ID_ESTADOIDFORMULARIO = FORMULARIO_RADICADO
          WHERE  NUMEROFORMULARIO = P_NRO_FORMULARIO;
        ELSE
          ID_USUARIOASIGNADO := pkg_common.F_USUARIOMENOSCARGA(LIDER_RADICADOR);
          PKG_COMMON.SP_UPDESTADO_DECLARACION(V_ID_DECLARACION, ID_USUARIOASIGNADO, RAD_PENDIENTE_POR_VERIFICAR);
        END IF;
      END IF;

      -- SI ES UNA DEVOLUCION NO SE DEBE ACTUALIZAR NI EL MUNICIPIO NI LA ENTIDAD
      IF P_NRO_ID_TIPO_RADICACION = TIPO_RADICACION_DEVOLUCION THEN
        UPDATE tbradicacion SET
          nro_formulario = P_NRO_FORMULARIO,
          id_tipo_radicacion = P_NRO_ID_TIPO_RADICACION,
          observaciones = P_OBSERVACIONES,
          rutaimagen = P_RUTAIMAGEN
        WHERE ID = P_ID;
      ELSE
        UPDATE tbradicacion SET
          id_municipio = P_ID_MUNICIPIO,
          param_tipoentidad = P_PARAM_TIPOENTIDAD,
          nro_formulario = P_NRO_FORMULARIO,
          id_tipo_radicacion = P_NRO_ID_TIPO_RADICACION,
          observaciones = P_OBSERVACIONES,
          rutaimagen = P_RUTAIMAGEN,
          id_entidadmunicipio = P_ID_ENTIDADMUNICIPIO
        WHERE ID = P_ID;
        UPDATE TBDECLARACIONES SET
          ID_PAISDECLARACION = V_PAISDECLARACION,
          ID_MUNICIPIODECLARACION = P_ID_MUNICIPIO,
          ID_DEPARTAMENTODECLARACION = V_DPTODECLARACION,
          ID_ENTIDADMUNICIPIODECLARACION = P_ID_ENTIDADMUNICIPIO
        WHERE ID = V_ID_DECLARACION;
      END IF; 

    EXCEPTION
    WHEN OTHERS THEN
        RAISE;
  END;

  /* OBTIENE LOS DATOS DE RADICACION Y DE DECLARACION A PARTIR DE UN ID_DECLARACION*/
  PROCEDURE SP_OBTENERRADFROMDECLA( PI_IDDECLARACION IN NUMBER,
                                    PO_RADICACION OUT CURSOR_TYPE
                                  ) IS

  NROFORM VARCHAR2(15);

  BEGIN
  OPEN  PO_RADICACION FOR
    SELECT  R.ID,
            R.FECHALLEGADA,
            R.NRO_FORMULARIO,
            R.ID_ENTIDADMUNICIPIO,
            R.ID_TIPO_RADICACION,
            R.PARAM_RESULTADO_VALIDACION,
            R.RUTAIMAGEN,
            R.OBSERVACIONES,
            PA.PRIMERNOMBRE,
            PA.SEGUNDONOMBRE,
            PA.PRIMERAPELLIDO,
            PA.SEGUNDOAPELLIDO,
            PA.PARAM_TIPODOCUMENTO,
            PA.NUMERODOCUMENTO
    FROM    TBRADICACION R
    INNER JOIN TBDECLARACIONES D ON R.ID_DECLARACION = D.ID
    INNER JOIN TBREGISTROS_PERSONAS RPA ON RPA.ID_DECLARACION = D."ID"
    INNER JOIN TBPERSONAS PA on PA."ID" = RPA.ID_PERSONA
    WHERE D.ID = PI_IDDECLARACION AND RPA.ESDECLARANTE = 1;

  END;

