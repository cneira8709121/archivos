  PROCEDURE SP_INSERTARADICACIONDEV
   (
    PI_FECHALLEGADA                 DATE,
    PI_IDUSUARIO                    NUMBER,
    PI_NUMEROFORMULARIO             VARCHAR2,
    P_OBSERVACIONES                 VARCHAR2 DEFAULT NULL,
    PO_IDRADICACION                 OUT NUMBER
   )
   AS
   TOMORROW                         DATE;
   FECHAEXCEPCION                   EXCEPTION;
   NOEXISTEDEVEXCEPCION             EXCEPTION;
   CANTIDAD                         NUMBER;
   V_ID_DECLARACION                 NUMBER;
   V_MAXID_DECLARACION              NUMBER;
   V_ESTADODECLANTERIOR             NUMBER;
   V_ID_USUARIO                     NUMBER;
   V_ID_VALORACION                  number := 0;
   V_ID_ENTIDADMUNICIPIO            TBRADICACION.ID_ENTIDADMUNICIPIO%TYPE;
   V_PARAM_TIPOENTIDAD              TBRADICACION.PARAM_TIPOENTIDAD%TYPE;
   V_ID_MUNICIPIO                   TBRADICACION.ID_MUNICIPIO%TYPE;
   BEGIN
      SELECT SEQ_RADICACION.NEXTVAL INTO PO_IDRADICACION FROM DUAL;
      SELECT to_date(to_char(sysdate,'yyyymmdd'),'yyyymmdd')INTO TOMORROW FROM DUAL;
      SELECT TOMORROW + 1 day INTO TOMORROW FROM DUAL;

      IF PI_FECHALLEGADA >= TOMORROW THEN
        RAISE FECHAEXCEPCION;
      END IF;

      --Busca la declaración
      SELECT      DC.ID
      INTO        V_ID_DECLARACION
      FROM        TBDECLARACIONES DC
      INNER JOIN  TBDEVOLUCION DV ON DV.ID_DECLARACION = DC.ID
      WHERE       DC.NUMEROFORMULARIO = PI_NUMEROFORMULARIO
          AND     ROWNUM = 1;

      IF (V_ID_DECLARACION = NULL) THEN
        RAISE NOEXISTEDEVEXCEPCION;
      END IF;

      -- SON SELECCIONADOS LOS PRINCIPALES DATOS DE LA ULTIMA RADICACION PARA SER
      -- INSERTADOS EN LA DE LA DEVOLUCION
      SELECT      R.ID_ENTIDADMUNICIPIO,
                  R.PARAM_TIPOENTIDAD,
                  R.ID_MUNICIPIO
      INTO        V_ID_ENTIDADMUNICIPIO,
                  V_PARAM_TIPOENTIDAD,
                  V_ID_MUNICIPIO
      FROM        TBDECLARACIONES D
      INNER JOIN  TBRADICACION R ON R.ID_DECLARACION = D.ID
      INNER JOIN  (
                    SELECT      MAX(R.FECHAREGISTRO) FECHAREGISTRO, R.ID_DECLARACION
                    FROM        TBRADICACION R
                    WHERE       R.ID_DECLARACION = V_ID_DECLARACION
                    GROUP BY    R.ID_DECLARACION
                  ) RD ON RD.FECHAREGISTRO = R.FECHAREGISTRO
      WHERE       D.ID = V_ID_DECLARACION;


      INSERT INTO tbradicacion
      (
        "ID",
        fecharegistro,
        fechallegada,
        id_usuario_radica,
        nro_formulario,
        id_declaracion,
        id_tipo_radicacion,
        observaciones,
        ID_ENTIDADMUNICIPIO,
        PARAM_TIPOENTIDAD,
        ID_MUNICIPIO,
        PARAM_RESULTADO_VALIDACION
      )
      VALUES
      (
        PO_IDRADICACION,
        SYSDATE,
        PI_FECHALLEGADA,
        PI_IDUSUARIO,
        PI_NUMEROFORMULARIO,
        V_ID_DECLARACION,
        TIPO_RADICACION_DEVOLUCION,
        P_OBSERVACIONES,
        V_ID_ENTIDADMUNICIPIO,
        V_PARAM_TIPOENTIDAD,
        V_ID_MUNICIPIO,
        VALIDACION_CORRECTA
      );

      SELECT COUNT(1)
      INTO   CANTIDAD
      FROM   TBIDENTIFICADORFORMULARIO I
      WHERE  I.NUMEROFORMULARIO = PI_NUMEROFORMULARIO;

      IF CANTIDAD > 0 THEN
         UPDATE tbidentificadorformulario
         SET    id_estadoidformulario = FORMULARIO_RADICADO
         WHERE  numeroformulario = PI_NUMEROFORMULARIO;
      END IF;

      --Busca el estado y el usuario que realizó la devolución de la declaración
      SELECT ESTADODECLANTERIOR, ID_USUARIOSOLICITANTE
      INTO V_ESTADODECLANTERIOR, V_ID_USUARIO
      FROM TBDEVOLUCION
      WHERE ID = (SELECT MAX(ID) FROM TBDEVOLUCION WHERE ID_DECLARACION = V_ID_DECLARACION);

      IF (V_ID_USUARIO IS NOT NULL) THEN

             IF V_ESTADODECLANTERIOR = 10001 then
                      PKG_VALORACION.SP_ASIGNARVALORACION(V_ID_VALORACION,V_ID_DECLARACION,2,V_ID_USUARIO,null);
                      PKG_COMMON.SP_UPDESTADO_DECLARACION(V_ID_DECLARACION, V_ID_USUARIO, V_ESTADODECLANTERIOR);
             ELSIF   V_ESTADODECLANTERIOR = 10000 then
                     PKG_VALORACION.SP_ASIGNARVALORACION(V_ID_VALORACION,V_ID_DECLARACION,1,V_ID_USUARIO,null);
                     PKG_COMMON.SP_UPDESTADO_DECLARACION(V_ID_DECLARACION, V_ID_USUARIO, V_ESTADODECLANTERIOR);
             ELSE
                 PKG_COMMON.SP_UPDESTADO_DECLARACION(V_ID_DECLARACION, V_ID_USUARIO, V_ESTADODECLANTERIOR);
             END IF;
      END IF;


    EXCEPTION
    WHEN FECHAEXCEPCION THEN
         DBMS_OUTPUT.PUT_LINE('La fecha no puede ser mayor a la fecha actual del sistema.');
         DBMS_OUTPUT.PUT_LINE('CUSTOM ERR001: SP_SETRADICACION ERR-FECHAEXCEPCION');
         RAISE_APPLICATION_ERROR(-20001, 'La fecha no puede ser mayor a la fecha actual del sistema ' || SYSDATE || '. CODE: SP_SETRADICACION ERR-FECHAEXCEPCION.');
    WHEN NOEXISTEDEVEXCEPCION THEN
         RAISE_APPLICATION_ERROR(-20001, 'No se encontrï¿½ una devoluciï¿½n relacionada con el nï¿½mero de formulario');
    WHEN OTHERS THEN
        RAISE;
  END;

END PKG_RADICACION;
