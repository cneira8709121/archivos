                                      PI_IDDECLARACION IN NUMBER,
                                      PO_RADICACION OUT CURSOR_TYPE
                                    ) IS
   NROFORM VARCHAR2(15);
  BEGIN

  SELECT RP.NRO_FORMULARIO INTO NROFORM FROM TBRADICACION RP WHERE RP.ID_DECLARACION = PI_IDDECLARACION;

  OPEN  PO_RADICACION FOR
    SELECT R.ID,
            R.FECHALLEGADA,
            R.NRO_FORMULARIO,
            R.ID_ENTIDADMUNICIPIO,
            R.ID_TIPO_RADICACION,
            R.PARAM_RESULTADO_VALIDACION,
            R.RUTAIMAGEN,
            R.OBSERVACIONES,
            PA.PRIMERNOMBRE,
            PA.SEGUNDONOMBRE,
            PA.PRIMERAPELLIDO,
            PA.SEGUNDOAPELLIDO,
            PA.PARAM_TIPODOCUMENTO,
            PA.NUMERODOCUMENTO
    FROM TBRADICACION R
    INNER JOIN TBDECLARACIONES D ON R.ID_DECLARACION = D.ID
    INNER JOIN TBREGISTROS_PERSONAS RPA ON RPA.ID_DECLARACION = D."ID"
    INNER JOIN TBPERSONAS PA ON PA."ID" = RPA.ID_PERSONA
    WHERE D.ID <> PI_IDDECLARACION AND RPA.ESDECLARANTE = 1 AND R.NRO_FORMULARIO = NROFORM;
  END;

