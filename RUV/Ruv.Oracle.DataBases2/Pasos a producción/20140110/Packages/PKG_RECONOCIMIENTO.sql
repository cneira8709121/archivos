 PROCEDURE sp_generaNroFrm
  (
       P_ID                   NUMBER
      --,P_idCreado            OUT NUMBER
  )
  AS
      v_id NUMBER;
      v_sum NUMBER;
      v_contador NUMBER;
      v_tam NUMBER;

      v_sum1 number;
      v_contador1 NUMBER;
      v_tam1 NUMBER;

      v_car2 varchar2(10);
      nro varchar2(50);
      cns varchar2(9);
  BEGIN

      v_sum := 0;
      select seq_nroformulario.nextval into v_id from dual;
      v_tam := length(v_id);
      for v_contador in 1..v_tam loop
          v_sum := v_sum + substr(v_id, v_contador,1);
      end loop;


      v_sum1 := 0;

      v_tam1 := length(v_sum);
      for v_contador1 in 1..v_tam1 loop
          v_sum1 := v_sum1 + substr(v_id, v_contador1,1);
      end loop;

      if (v_sum1 = 1) then
        v_car2 := 'M';
      elsif (v_sum1 = 2) then
        v_car2 := 'L';
      elsif (v_sum1 = 3) then
        v_car2 := 'K';
      elsif (v_sum1 = 4) then
        v_car2 := 'J';
      elsif (v_sum1 = 5) then
        v_car2 := 'I';
      elsif (v_sum1 = 6) then
        v_car2 := 'H';
      elsif (v_sum1 = 7) then
        v_car2 := 'G';
      elsif (v_sum1 = 8) then
        v_car2 := 'F';
      elsif (v_sum1 = 9) then
        v_car2 := 'E';
      elsif (v_sum1 = 10) then
        v_car2 := 'D';
      elsif (v_sum1 = 11) then
        v_car2 := 'C';
      else
        v_car2 := 'Z';
      end if;

      SELECT LPAD(v_id,9,'0') into cns from dual; --relleno_izquierda

      nro := 'B' || v_car2 || cns;

      update tbdeclaraciones set numeroformulario = nro
      where id = p_id;


    --p_idCreado := v_id;

       COMMIT;
  EXCEPTION
    WHEN OTHERS THEN
      ROLLBACK;
      RAISE;

  END;

