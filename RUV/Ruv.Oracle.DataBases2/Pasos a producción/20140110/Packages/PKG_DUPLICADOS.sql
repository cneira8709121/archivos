  --Retorna los numeros de formulario repetidos.
  PROCEDURE sp_GetDeclaraciones(po_Cursor OUT SYS_REFCURSOR) IS
  BEGIN
  
    OPEN PO_CURSOR FOR
      SELECT * FROM (
        SELECT numeroformulario, count(numeroformulario) CONTEO FROM tbdeclaraciones 
        GROUP BY numeroformulario
        ) 
      WHERE CONTEO > 1
      ORDER BY CONTEO, NUMEROFORMULARIO;
  
  END;

  PROCEDURE sp_PersonasIdCriterio(po_Cursor OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN PO_CURSOR FOR
      SELECT  NUMERODOCUMENTO, 
              PRIMERNOMBRE,
              SEGUNDONOMBRE,
              PRIMERAPELLIDO,
              SEGUNDOAPELLIDO, 
              COUNT(1)
      FROM TBPERSONAS
      WHERE NUMERODOCUMENTO IS NOT NULL
      GROUP BY  NUMERODOCUMENTO, 
                PRIMERNOMBRE,
                SEGUNDONOMBRE,
                PRIMERAPELLIDO,
                SEGUNDOAPELLIDO
      HAVING COUNT(1) > 1;
  END;
  
